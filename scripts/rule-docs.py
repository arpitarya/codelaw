def section_table(section, prefix_name):
    rows = ["| Key | Type | Default | What it does |", "|---|---|---|---|"]

    def walk(props, prefix):
        for k, v in props.items():
            key = prefix + k
            if v.get("type") == "object" and "properties" in v:
                rows.append("| `[{}.{}]` | table | — | {} |".format(prefix_name, key, (v.get("description") or "").replace("|", "\\|")))
                walk(v["properties"], key + ".")
                continue
            kind = v.get("type") or ("enum" if "enum" in v else "integer or string" if "oneOf" in v else "")
            if "enum" in v:
                kind = " · ".join("`{}`".format(x) for x in v["enum"])
            else:
                kind = "`{}`".format(kind)
            d = "`{}`".format(tval(v["default"])) if "default" in v else "—"
            rows.append("| `{}` | {} | {} | {} |".format(key, kind, d, (v.get("description") or "").replace("|", "\\|")))
    walk(section.get("properties", {}), "")
    return "\n".join(rows)


