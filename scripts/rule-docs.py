def turned_on_by(ctx, rid):
    """[(preset, severity)] in pack order."""
    out = []
    for pack in package.PACKS:
        for p in ctx.preset_order.get(pack, []):
            sev = ctx.presets[p]["effective"].get(rid)
            if sev is not None:
                out.append((p, sev))
    return out


def md_title(title):
    """A title as Markdown text: brackets outside code spans are not a link."""
    parts = re.split(r"(`+[^`]*?`+)", title)
    return "".join(p if p.startswith("`") else p.replace("[", "\\[").replace("]", "\\]") for p in parts).replace("|", "\\|")


def lang_names(langs):
    return ", ".join(LANG[l][0] if l in LANG else l for l in langs)


def rel_link(target, doc_dir):
    return os.path.relpath(str(ROOT / target), str(doc_dir)).replace(os.sep, "/")


def fence(tag, body):
    ticks = "````" if "```" in body else "```"
    return "{}{}\n{}\n{}".format(ticks, tag, body.rstrip("\n"), ticks)


def options_table(fm):
    opts = fm.get("options") or {}
    rows = ["| Option | Type | Default | What it does |", "|---|---|---|---|"]
    for name, spec in opts.items():
        default = spec.get("default")
        if spec.get("type") == "call[]":
            dshow = "{} entries (below)".format(len(default or [])) if default else "`[]`"
        else:
            dshow = "*none*" if default is None else "`{}`".format(tval(default).replace("|", "\\|"))
        desc = (spec.get("description") or "*not described in the rule file*").replace("|", "\\|")
        rows.append("| `{}` | `{}` | {} | {} |".format(name, spec.get("type"), dshow, desc))
        if spec.get("type") == "call[]":
            rows.append("| `{}_mode` | `string` | `\"extend\"` | `extend` adds your `{}` to the default list; `replace` uses only yours |".format(name, name))
    return "\n".join(rows)


def defaults_block(rid, fm):
    lines = ["[rules.{}]".format(tstr(rid)), 'severity = "{}"'.format(fm.get("severity", "error")), "",
             "[rules.{}.options]".format(tstr(rid))]
    for name, spec in (fm.get("options") or {}).items():
        default = spec.get("default")
        if default is None:
            lines.append("# {} = …   # no default: unset".format(name))
        else:
            lines.append("{} = {}".format(name, tval(default)))
        if spec.get("type") == "call[]":
            lines.append('{}_mode = "extend"'.format(name))
    return "\n".join(lines)


def scope_example(fm, packs):
    langs = fm.get("languages") or []
    ext = LANG[langs[0]][1] if langs and langs[0] in LANG else "*"
    if any(p in ("js", "react", "ts", "node", "stencil", "tanstack-query", "redux-toolkit", "security-js", "security-ts") for p in packs) and ext in ("js", "jsx", "ts", "tsx"):
        return "tests", None, "the `tests` scope `codelaw:js/recommended` ships (`**/*.test.*`, `**/*.spec.*`); naming it extends it, so its files stay"
    if "python" in packs or "security-python" in packs:
        return "tests", None, "the `tests` scope `codelaw:py/recommended` ships (`**/tests/**`, `**/test_*.py`, `**/*_test.py`); naming it extends it, so its files stay"
    return "legacy", ['src/legacy/**/*.{}'.format(ext)], "a scope of your own needs `files`"


def suppression_lines(rid, langs):
    forms, seen = [], set()
    for l in langs:
        if l not in LANG:
            continue
        form = LANG[l][2]
        key = form or "none"
        if key in seen:
            continue
        seen.add(key)
        forms.append((l, form))
    return forms


