def example_value(rid, name, spec, cases):
    """An illustrative value for one option, and where it came from."""
    kind, default = spec.get("type"), spec.get("default")
    desc = spec.get("description") or ""
    eg = re.search(r'e\.g\.\s*(\[[^\]]*\]|"[^"]*")', desc)
    if eg:
        try:
            return json.loads(eg.group(1))
        except ValueError:
            pass
    for c in cases:  # a case that tests a bad value is not an example to copy
        if name in c[3] and c[3][name] != default and not re.search(r"invalid|malformed|bad |wrong|not a ", c[0], re.I):
            return c[3][name]
    if kind == "boolean":
        return not default if isinstance(default, bool) else True
    if kind in ("integer", "number"):
        if isinstance(default, (int, float)) and not isinstance(default, bool) and default > 0:
            return default * 2
        return 3
    if kind == "string":
        ticks = [t for t in re.findall(r"`([^`]+)`", desc) if t != default and re.match(r"^[\w.-]+$", t)]
        if len(re.findall(r"`([^`]+)`", desc)) >= 2 and ticks:
            return ticks[0]
        if default:
            return default
        return "<your value>"
    if kind in ("string[]", "number[]"):
        if default:
            return default
        such = re.search(r"such as (.*)", desc)
        if such:
            ticks = re.findall(r"`([^`/]+)`", such.group(1))
            if ticks:
                return ticks
        return ["<name>"]
    if kind == "call[]":
        if name == "validators":
            return [{"name": "parseInput", "module": "@acme/validation"}]
        return [{"name": "sanitizeHtml", "module": "@acme/security"}]
    if kind == "object":
        return default if default else {}
    return default


